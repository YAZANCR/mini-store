<?php

require_once __DIR__ . '/functions.php';


// =====================================================
// التأكد من تسجيل الدخول
// =====================================================

require_login();


// =====================================================
// السماح بطلبات POST فقط
// =====================================================

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    redirect('products.php');
}


// =====================================================
// التحقق من CSRF
// =====================================================

check_csrf();


// =====================================================
// استقبال البيانات
// =====================================================

$id = (int) ($_POST['product_id'] ?? 0);

$quantity = max(
    1,
    (int) ($_POST['quantity'] ?? 1)
);

$phone = trim(
    $_POST['phone'] ?? ''
);


// =====================================================
// بدء المعاملة Transaction
// =====================================================

$pdo = db();

$pdo->beginTransaction();


try {

    // =================================================
    // جلب المنتج والتأكد من توفر الكمية
    // =================================================

    $q = $pdo->prepare("
        SELECT *
        FROM products
        WHERE id = ?
          AND stock >= ?
        FOR UPDATE
    ");

    $q->execute([
        $id,
        $quantity
    ]);

    $product = $q->fetch();


    // =================================================
    // التحقق من المنتج ورقم الجوال
    // =================================================

    if (
        !$product ||
        !preg_match(
            '/^[0-9+\-() ]{7,30}$/',
            $phone
        )
    ) {

        $pdo->rollBack();

        flash(
            'المنتج غير متوفر أو البيانات غير صحيحة.',
            'error'
        );

        redirect('products.php');
    }


    // =================================================
    // إنشاء الطلب
    // =================================================

    $o = $pdo->prepare("
        INSERT INTO orders
        (
            user_id,
            product_id,
            quantity,
            product_url,
            phone,
            notes
        )
        VALUES (?, ?, ?, ?, ?, ?)
    ");


    $o->execute([
        user()['id'],
        $id,
        $quantity,
        null,
        $phone,
        'طلب منتج فوري'
    ]);


    // =================================================
    // خصم الكمية من المخزون
    // =================================================

    $u = $pdo->prepare("
        UPDATE products
        SET stock = stock - ?
        WHERE id = ?
    ");

    $u->execute([
        $quantity,
        $id
    ]);


    // =================================================
    // تأكيد العملية
    // =================================================

    $pdo->commit();


    flash(
        'تم تسجيل طلب المنتج الفوري بنجاح.'
    );


    redirect('my_orders.php');


} catch (Throwable $e) {

    // في حالة حدوث خطأ يتم التراجع
    if ($pdo->inTransaction()) {
        $pdo->rollBack();
    }


    flash(
        'تعذر تسجيل الطلب حاليًا.',
        'error'
    );


    redirect('products.php');
}