<?php

require_once __DIR__ . '/functions.php';


// =====================================================
// التأكد من تسجيل الدخول
// =====================================================

require_login();


// =====================================================
// السماح بطلبات POST فقط
// =====================================================

if ($_SERVER['REQUEST_METHOD'] !== 'POST') {
    redirect('index.php');
}


// =====================================================
// التحقق من CSRF
// =====================================================

check_csrf();


// =====================================================
// استقبال البيانات
// =====================================================

$store = (int) ($_POST['store_id'] ?? 0);

$url = trim(
    $_POST['product_url'] ?? ''
);

$phone = trim(
    $_POST['phone'] ?? ''
);

$notes = trim(
    $_POST['notes'] ?? ''
);


// =====================================================
// التحقق من البيانات الأساسية
// =====================================================

if (
    !$store ||
    !filter_var($url, FILTER_VALIDATE_URL) ||
    !preg_match('/^[0-9+\-() ]{7,30}$/', $phone)
) {

    flash(
        'تأكد من اختيار المتجر وصحة الرابط ورقم الجوال.',
        'error'
    );

    redirect('index.php#order');
}


// =====================================================
// التأكد من وجود المتجر
// =====================================================

$storeCheck = db()->prepare(
    'SELECT id FROM stores WHERE id = ? LIMIT 1'
);

$storeCheck->execute([
    $store
]);


if (!$storeCheck->fetch()) {

    flash(
        'المتجر المحدد غير موجود.',
        'error'
    );

    redirect('index.php#order');
}


// =====================================================
// إضافة الطلب إلى قاعدة البيانات
// =====================================================

$q = db()->prepare("
    INSERT INTO orders
    (
        user_id,
        store_id,
        product_url,
        phone,
        notes
    )
    VALUES (?, ?, ?, ?, ?)
");


$q->execute([
    user()['id'],
    $store,
    $url,
    $phone,
    $notes
]);


// =====================================================
// رسالة النجاح
// =====================================================

flash(
    'تم إرسال طلبك بنجاح.'
);


// =====================================================
// الانتقال إلى طلباتي
// =====================================================

redirect('my_orders.php');